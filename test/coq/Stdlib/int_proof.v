Section StdlibDef.

  (* Basic arithmetic. *)

  Definition Stdlib__add := VClo2 EIntAdd.
  Definition Stdlib__sub := VClo2 EIntSub.
  Definition Stdlib__neg := VClo1 EIntNeg.
    Definition Stdlib__lt : val := VClo2 EOpLt.
    Definition Stdlib__le : val := VClo2 EOpLe.
    Definition Stdlib__gt : val := VClo2 EOpGt.
    Definition Stdlib__ge : val := VClo2 EOpGe.


  Definition stdlib_arith :=
    EnvCons "+" Stdlib__add $
            EnvCons "-" Stdlib__sub $
            EnvCons "<" Stdlib__lt $
            EnvCons "<=" Stdlib__le $
            EnvCons ">" Stdlib__gt $
            EnvCons ">=" Stdlib__ge $
            EnvCons "~-" Stdlib__neg $
            EnvNil.

  (* ------------------------------------------------------------------------ *)

  Definition Stdlib__lsr := VClo2 EIntAdd.

  Definition Stdlib__eq := VClo2 EOpEq.
  Definition Stdlib__ne : val := VClo2 EOpNe.
  Axiom Stdlib__compare : val.

  Definition stdlib_misc :=
    EnvCons "lsr" Stdlib__lsr $
            EnvCons "=" Stdlib__eq $
            EnvCons "<>" Stdlib__ne $
            EnvCons "compare" Stdlib__compare $
            EnvNil.

  (* ------------------------------------------------------------------------ *)

  Definition Stdlib :=
    VStruct $
            stdlib_arith :::
            stdlib_misc.

  Definition HasStdlib (η : env) : Prop :=
    lookup_name η "Stdlib" = Ret Stdlib.
End StdlibDef.

